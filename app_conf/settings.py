def _env(name, default=None):
    """Read a setting from the environment, falling back to .env via python-decouple."""
    value = os.environ.get(name)
    if value is not None:
        return value
    if _env_config is not None:
        try:
            return _env_config(name, default=default)
        except Exception:
            pass
    return default


def _env_bool(name, default=False):
    """Read a boolean environment value without treating typos as False."""
    value = _env(name, default)
    if value is None or (
        isinstance(value, str) and not value.strip()
    ):
        value = default
    if isinstance(value, bool):
        return value
    normalized = str(value).strip().lower()
    if normalized in ('1', 'true', 'yes', 'on'):
        return True
    if normalized in ('0', 'false', 'no', 'off'):
        return False
    raise ImproperlyConfigured(f'{name} must be a boolean value.')


